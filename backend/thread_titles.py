"""Conversation titles — pure helpers (no LLM/DB imports, unit-testable).

Titles are generated ONCE per thread and persisted in auth.db
(thread_owners.title), instead of being re-generated by the LLM for every
thread on every history load. That old behaviour fired one LLM call per
conversation each time the sidebar loaded; under Groq rate limits most of
those failed and silently fell back to "New Conversation".

Rules:
  * A short first message (< SHORT_MESSAGE_LEN chars) is its own title — no
    LLM call needed for "hi" or "pandas help".
  * Longer messages get an LLM title. Only a successful LLM title (or a short
    message) is persisted.
  * If the LLM fails, the first message itself is shown (truncated) but NOT
    persisted, so a later load can still produce a proper title.
  * A title the user typed (rename) always wins and is never overwritten.
"""
from __future__ import annotations

import re
from typing import Callable, Optional, Tuple

DEFAULT_TITLE = "New Conversation"
SHORT_MESSAGE_LEN = 15      # below this, the message itself is the title
FALLBACK_LEN = 42           # truncation for message-derived titles
MAX_GENERATED_LEN = 48      # LLM titles are asked for 3-5 words; cap runaways
MAX_USER_TITLE_LEN = 80     # renames typed by the user

# The frontend sends file uploads to the model as:
#   "<user text>\n\n[Attached pdf: report.pdf]\n\"\"\"\n<extracted text>\n\"\"\""
# or, with no typed text, starting directly with "[Attached ...]".
_ATTACH_RE = re.compile(r"^\[Attached [^:\]]+: (?P<name>[^\]\n]+)\]")
_PREFIX_RE = re.compile(r"^(title|conversation title)\s*:\s*", re.IGNORECASE)


def _truncate(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _squash(text: str) -> str:
    return " ".join(text.split())


def title_source(content) -> str:
    """The part of a first user message worth titling: the typed text, or the
    attached file's name — never the extracted file contents."""
    text = content if isinstance(content, str) else str(content or "")
    text = text.strip()
    m = _ATTACH_RE.match(text)
    if m:
        return _squash(m.group("name"))
    return _squash(text.split("\n\n[Attached ", 1)[0])


def clean_generated_title(raw) -> Optional[str]:
    """Normalise an LLM title; None if nothing usable came back."""
    t = _squash(str(raw or ""))
    t = _PREFIX_RE.sub("", t)
    t = t.strip(" \"'`*#.").strip()
    if not t:
        return None
    return _truncate(t, MAX_GENERATED_LEN)


def fallback_title(source: str) -> str:
    source = _squash(source or "")
    return _truncate(source, FALLBACK_LEN) if source else DEFAULT_TITLE


def make_title(source: str, generate: Optional[Callable[[str], Optional[str]]]) -> Tuple[str, bool]:
    """Return (title, persist). `persist` is False when the title is only a
    stand-in (LLM unavailable) and should be retried on a later load."""
    source = _squash(source or "")
    if not source:
        return DEFAULT_TITLE, False
    if len(source) < SHORT_MESSAGE_LEN:
        return source, True
    generated = None
    if generate is not None:
        try:
            generated = clean_generated_title(generate(source))
        except Exception:
            generated = None
    if generated:
        return generated, True
    return fallback_title(source), False


def normalize_user_title(value) -> str:
    """Validate a title typed by the user. Raises ValueError (→ HTTP 422)."""
    t = _squash(str(value or ""))
    if not t:
        raise ValueError("Title can't be empty.")
    if len(t) > MAX_USER_TITLE_LEN:
        raise ValueError(f"Title must be {MAX_USER_TITLE_LEN} characters or fewer.")
    return t
